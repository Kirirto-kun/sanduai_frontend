export function trainingMarkdown(result: TrainingResult): string {
  const labels = result.language === "kk" ? KK : result.language === "ru" ? RU : OTHER_LABELS[result.language];
  const locale = result.language === "kk" ? "kk" : "ru";
  const otherIndex = ["en", "ky", "uz"].indexOf(result.language);
  const enumValue = (value: string, fallback: string) => otherIndex < 0 ? fallback : OTHER_ENUMS[value]?.[otherIndex] ?? value.replaceAll("_", " ");
  const displayValues: Record<string, string> = {
    event_type: enumValue(result.event_type, EVENTS.find(item => item.id === result.event_type)?.[locale] ?? result.event_type),
    output_mode: enumValue(result.output_mode, MODES.find(item => item.id === result.output_mode)?.[locale] ?? result.output_mode),
    format: enumValue(result.format, ({ offline: { kk: "Офлайн", ru: "Офлайн" }, online: { kk: "Онлайн", ru: "Онлайн" }, hybrid: { kk: "Аралас", ru: "Смешанный" } } as const)[result.format as "offline" | "online" | "hybrid"]?.[locale] ?? result.format),
    language: contentLanguageLabel(result.language),
  };
  function serialize(value: unknown, depth: number): string {
    if (value === null || value === undefined || value === "") return "";
    if (Array.isArray(value)) return value.map((v, i) => typeof v === "string" ? `- ${v}` : `\n${"#".repeat(Math.min(depth, 6))} ${i + 1}\n\n${serialize(v, depth + 1)}`).join("\n");
    if (typeof value === "object") return Object.entries(value).filter(([key]) => !["id", "cost_tokens"].includes(key)).map(([key, val]) => {
      const body = depth === 2 && typeof val === "string" && displayValues[key] ? displayValues[key] : serialize(val, depth + 1); if (!body) return "";
      const label = labels[key] ?? key.replaceAll("_", " ");
      return typeof val === "object" ? `\n${"#".repeat(Math.min(depth, 6))} ${label}\n\n${body}\n` : `**${label}:** ${body}\n`;
    }).join("\n");
    return String(value);
  }
  return `# ${result.title}\n\n${serialize(Object.fromEntries(Object.entries(result).filter(([key]) => key !== "title")), 2)}\n`;
}
